def cell_image(name):
    """칸 이름 → 16×16 RGBA (팔레트 색만)."""
    _, ink, rows = CELLS[name]
    if len(rows) != 16 or any(len(r) != 16 for r in rows):
        raise ValueError(f"칸 {name} 은 16×16 이어야 한다")
    img = Image.new("RGBA", (16, 16))
    px = img.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch not in ink:
                raise ValueError(f"칸 {name}: 모르는 글자 {ch!r} ({x},{y})")
            px[x, y] = c(ink[ch])
    return img


class HandMat(Mat):
    """손으로 찍은 칸을 쓰는 재료. light: 요소의 light_emission (0 이면 없음, 쇠단지 불씨만)."""

    def __init__(self, name, light=0):
        _, ink, _ = CELLS[name]
        ramp = [c(v) for v in list(dict.fromkeys(ink.values()))[:4]]
        super().__init__(ramp, style="flat", glow=False)
        self.cell_name = name
        self.light = light
        self._img = cell_image(name)

    def cell(self, frame=0, frames=1):
        return self._img.copy()


def mats(*names, alias=None, light=None):
    """{재료 이름: HandMat}. alias = {새 이름: 칸 이름} 으로 같은 칸을 다른 이름으로 (복셀 칠을 나눌 때)."""
    out = {n: HandMat(n, (light or {}).get(n, 0)) for n in names}
    for k, v in (alias or {}).items():
        out[k] = HandMat(v, (light or {}).get(k, 0))
    return out


# ─────────────────────────── 칸 경계를 옮긴 복셀 무기 ───────────────────────────

def _tile_end(i, shift):
    """i 가 든 칸의 끝 (이 칸 경계를 넘지 않는다)."""
    return ((i - shift) // 16 + 1) * 16 + shift


class VoxWeapon(Weapon):
    """
    SPEC 1.2 의 격자와 쥐는 점. Z 칸 경계를 Z_TILE_SHIFT 만큼 옮겨 가운데에 놓인 것이 앞뒤로 쪼개지지 않게 한다.
    display 는 늘 build(..., display=...) 로 넘긴다 (wkit 의 옛 길이 맞춤 _display 는 쓰지 않는다, SPEC 1.2).
    """

    def __init__(self, mats_, seed=0, kind="souls"):
        super().__init__(mats_, kind=kind, seed=seed, grid=GRID, pivot=PIVOT)

    def _mesh(self, model, cells, g, opaque):
        used = np.zeros_like(g, dtype=bool)
        zs = Z_TILE_SHIFT
        for z in range(self.D):
            for y in range(self.H):
                for x in range(self.W):
                    m = g[x, y, z]
                    if m == 0 or used[x, y, z]:
                        continue
                    xe, ye, ze = _tile_end(x, 0), _tile_end(y, 0), _tile_end(z, zs)
                    x1 = x
                    while x1 + 1 < min(self.W, xe) and g[x1 + 1, y, z] == m and not used[x1 + 1, y, z]:
                        x1 += 1
                    y1 = y
                    while y1 + 1 < min(self.H, ye) and np.all(g[x:x1 + 1, y1 + 1, z] == m) and not used[x:x1 + 1, y1 + 1, z].any():
                        y1 += 1
                    z1 = z
                    while z1 + 1 < min(self.D, ze) and np.all(g[x:x1 + 1, y:y1 + 1, z1 + 1] == m) and not used[x:x1 + 1, y:y1 + 1, z1 + 1].any():
                        z1 += 1
                    used[x:x1 + 1, y:y1 + 1, z:z1 + 1] = True
                    self._emit(model, cells, m, x, y, z, x1, y1, z1, opaque)

    def _emit(self, model, cells, m, x0, y0, z0, x1, y1, z1, filled):
        name = self.names[m - 1]
        key, reg = cells[name]
        mat = self.mats[name]
        zs = Z_TILE_SHIFT

        def exposed(sl):
            part = filled[sl]
            return part.size == 0 or not part.all()

        faces = {}
        bx, by, bz = slice(x0, x1 + 1), slice(y0, y1 + 1), slice(z0, z1 + 1)
        if z1 + 1 >= self.D or exposed((bx, by, z1 + 1)):
            faces["south"] = (x0, x1 + 1, y0, y1 + 1, "xy", False, 0)
        if z0 - 1 < 0 or exposed((bx, by, z0 - 1)):
            faces["north"] = (x0, x1 + 1, y0, y1 + 1, "xy", True, 0)
        if x1 + 1 >= self.W or exposed((x1 + 1, by, bz)):
            faces["east"] = (z0, z1 + 1, y0, y1 + 1, "zy", True, zs)
        if x0 - 1 < 0 or exposed((x0 - 1, by, bz)):
            faces["west"] = (z0, z1 + 1, y0, y1 + 1, "zy", False, zs)
        if y1 + 1 >= self.H or exposed((bx, y1 + 1, bz)):
            faces["up"] = (x0, x1 + 1, z0, z1 + 1, "xz", False, zs)
        if y0 - 1 < 0 or exposed((bx, y0 - 1, bz)):
            faces["down"] = (x0, x1 + 1, z0, z1 + 1, "xz", False, zs)
        if not faces:
            return
        s = 16.0 / reg.atlas.size
        out = {}
        for f, (a0, a1, b0, b1, plane, flip, shift) in faces.items():
            ua = (a0 - shift) % 16 if plane == "zy" else a0 % 16
            u0, u1 = ua, ua + (a1 - a0)
            if plane in ("xy", "zy"):
                v0 = 16 - ((b1 - 1) % 16) - 1
                v1 = v0 + (b1 - b0)
            else:
                v0 = (b0 - shift) % 16
                v1 = v0 + (b1 - b0)
            if flip:
                u0, u1 = u1, u0
            uv = [round((reg.x + u0) * s, 4), round((reg.y + v0) * s, 4), round((reg.x + u1) * s, 4), round((reg.y + v1) * s, 4)]
            out[f] = (key, uv)
        frm = (8 + (x0 - self.CX) * self.VOX, self.Y0 + (y0 - self.CY) * self.VOX, 8 + (z0 - self.CZ) * self.VOX)
        to = (8 + (x1 + 1 - self.CX) * self.VOX, self.Y0 + (y1 + 1 - self.CY) * self.VOX, 8 + (z1 + 1 - self.CZ) * self.VOX)
        model.box(frm, to, out, light=getattr(mat, "light", 0))


def sheet(path, scale=8):
    """칸 전부를 한 장에 (이름 아래 줄)."""
    from PIL import ImageDraw
    names = list(CELLS)
    cols = 6
    rows = (len(names) + cols - 1) // cols
    cw, ch = 16 * scale + 16, 16 * scale + 22
    img = Image.new("RGB", (cols * cw, rows * ch), (20, 19, 18))
    d = ImageDraw.Draw(img)
    for i, n in enumerate(names):
        x, y = (i % cols) * cw + 8, (i // cols) * ch + 4
        img.paste(cell_image(n).resize((16 * scale, 16 * scale), Image.NEAREST), (x, y))
        d.text((x, y + 16 * scale + 3), n, fill=(200, 190, 170))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path)
    return path


