def _flask(fill, inner):
    """물약 style 하나 → 그림 함수. 채움 → edge() (유리·코르크·마개·목테가 저마다 자기 램프로 테두리) → 안쪽 지도."""
    def draw(ctx):
        s = {'main': 'glass', 'acc': POTION.get(ctx.iid, ctx.acc), 'acc2': 'cn_cork', 'acc3': 'cn_brass'}
        fills, inners = [fill], [inner]
        if ctx.iid in TONICS:
            s['acc3'] = 'cn_twine'
            fills.append(TONIC_TAG)
            inners.append(TONIC_TAG_IN)
        if ctx.iid == 'elixir_of_renewal':
            s['acc3'] = 'gold'
        img = paint(s, *fills)
        img = edge(img, [s['main'], s['acc'], s['acc2'], s['acc3']])
        img = paint(s, *inners, img=img)
        if ctx.iid == 'cleansing_draught':
            img = paint(s, BUBBLES, img=img)
        if ctx.iid == 'elixir_of_renewal':
            img = sparkle(img, 12, 3, arm='#ffc8ff')       # 팔 = 물 램프 5번 칸 (색을 늘리지 않는다)
        return img
    return draw


