@register('scroll')
def _scroll(ctx):
    s = SCROLLS.get(ctx.iid) or {'main': 'cn_parch', 'acc': 'cn_parch', 'acc3': ctx.acc}
    img = paint(s, SCROLL)
    img = edge(img, [s['main'], s['acc']])
    return paint(s, SCROLL_IN, TEXT, RIBBON, img=img)
