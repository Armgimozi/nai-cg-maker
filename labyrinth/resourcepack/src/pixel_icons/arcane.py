NAMES: dict[str, str] = {}


def icon(iid, name, slots, *maps, legend=None, rim=False):
    """아이템 id · 한글 이름(설명용) · slot→램프 이름 · 지도들 (차례로 덮음).
    rim=True 면 첫 지도를 칠한 뒤 edge() 로 R4 테두리 (위·왼쪽 2 / 아래·오른쪽 0, 그 물체 자기 램프)."""
    NAMES[iid] = name
    if not rim:
        return register_maps(iid, slots, *maps, legend=legend, group='arcane')
    img = edge(paint(slots, maps[0], legend=legend), list(slots.values()))
    if len(maps) > 1:
        img = paint(slots, *maps[1:], legend=legend, img=img)
    register(iid, lambda ctx, _i=img: _i.copy(), group='arcane')
    return img


def grid(text):
    """여러 줄 문자열 → 16×16 지도 (모자란 줄은 비움). 줄 길이가 16 이 아니면 오류 — 지도 오타를 바로 잡는다."""
    out = [ln.strip() for ln in text.strip('\n').split('\n')]
    out = [ln.ljust(16, '.') for ln in out]
    while len(out) < 16:
        out.append(E)
    if len(out) != 16 or any(len(ln) != 16 for ln in out):
        raise ValueError(f'bad arcane map: {out!r}')
    return out


