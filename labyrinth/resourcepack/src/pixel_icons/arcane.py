NAMES: dict[str, str] = {}


def grid(text):
    """여러 줄 문자열 → 16×16 지도 (모자란 칸·줄은 비움). 16글자를 넘는 줄이 있으면 오류 — 지도 오타를 바로 잡는다."""
    out = [ln.strip() for ln in text.strip('\n').split('\n')]
    if len(out) > 16 or any(len(ln) > 16 for ln in out):
        raise ValueError(f'bad arcane map: {out!r}')
    out = [ln.ljust(16, '.') for ln in out]
    while len(out) < 16:
        out.append(E)
    return out


def icon(iid, name, slots, fill, *over, rim=False):
    """아이템 id · 한글 이름(설명용) · slot→램프 이름 · 채움 지도 (+ 덧칠 지도들).
    rim=True 면 채움을 칠한 뒤 edge() 로 R4 테두리 (위·왼쪽 2 / 아래·오른쪽 0, 그 물체 자기 램프)."""
    NAMES[iid] = name
    img = paint(slots, fill)
    if rim:
        img = edge(img, list(slots.values()))
    if over:
        img = paint(slots, *over, img=img)
    register(iid, lambda ctx, _i=img: _i.copy(), group='arcane')
    return img


