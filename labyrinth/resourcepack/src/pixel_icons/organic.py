from __future__ import annotations

from . import E, add_ramps, edge, paint, register, register_maps, rows  # noqa: F401


NAMES: dict[str, str] = {}


def icon(iid, name, slots, *maps, legend=None):
    """C 시안의 icon(): 아이템 id · 한글 이름(설명용) · slot→램프 이름 · 지도들 (지도 그대로, 테두리 손으로)."""
    NAMES[iid] = name
    return register_maps(iid, slots, *maps, legend=legend, group='organic')


def drawn(iid, name, slots, fill, *over, legend=None, lit=2, shade=0, rim=True):
    """채움 지도 → edge() 로 R4 테두리(위·왼쪽 lit, 아래·오른쪽 shade, 그 물체 자기 램프) → 덧칠 지도들.
    rim=False 면 테두리를 자동으로 바꾸지 않는다 (가는 선 그림)."""
    NAMES[iid] = name
    img = paint(slots, fill, legend=legend)
    if rim:
        img = edge(img, list(slots.values()), lit=lit, shade=shade)
    if over:
        img = paint(slots, *over, legend=legend, img=img)
    register(iid, lambda ctx, _i=img: _i.copy(), group='organic')
    return img


