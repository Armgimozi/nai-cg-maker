def drawn(iid, name, slots, fill, *over, legend=None, rim=True, lit=2, shade=0):
    """채움 지도 → edge() 로 R4 테두리 (위·왼쪽 lit, 아래·오른쪽 shade, 그 물체 자기 램프) → 덧칠 지도들.
    rim=False 면 테두리를 손으로 칠한 그대로 둔다 (가는 선 그림)."""
    NAMES[iid] = name
    img = paint(slots, fill, legend=legend)
    if rim:
        img = edge(img, list(slots.values()), lit=lit, shade=shade)
    if over:
        img = paint(slots, *over, legend=legend, img=img)
    register(iid, lambda ctx, _i=img: _i.copy(), group='crafted')
    return img


