from __future__ import annotations

from . import Art, add_ramps, edge, paint, register

NAMES: dict[str, str] = {}


def rows(text: str) -> list[str]:
    """여러 줄 문자열 → 16×16 지도 (모자란 칸·줄은 비움). 16글자를 넘는 줄은 오류."""
    out = [ln.strip() for ln in text.strip('\n').split('\n')]
    if len(out) > 16 or any(len(ln) > 16 for ln in out):
        raise ValueError(f'crafted map too big: {out!r}')
    out = [ln.ljust(16, '.') for ln in out]
    while len(out) < 16:
        out.append('.' * 16)
    return out


def drawn(iid, name, slots, fill, *over, legend=None, rim=True, lit=2, shade=0):
    """채움 지도 → edge() 로 R4 테두리 (위·왼쪽 lit, 아래·오른쪽 shade, 그 물체 자기 램프) → 덧칠 지도들.
    rim=False 면 테두리를 손으로 칠한 그대로 둔다 (가는 선 그림)."""
    NAMES[iid] = name
    img = paint(slots, fill, legend=legend)
    if rim:
        img = edge(img, list(slots.values()), lit=lit, shade=shade)
    if over:
        img = paint(slots, *over, legend=legend, img=img)
    register(iid, lambda ctx, _i=img: _i.copy(), group='crafted')
    return img


