def _rune(top):
    """갈고리 룬 (위 오른쪽으로 꺾인 홈 → 세로 홈 → 아래 왼쪽으로 꺾인 홈), top = 시작 줄."""
    m = ['.' * 16] * top + [
        '.......cc.......',
        '.......c4.......',
        '.......c4.......',
        '.......c4.......',
        '......cc4.......',
        '.......44.......',
    ]
    return (m + ['.' * 16] * 16)[:16]


