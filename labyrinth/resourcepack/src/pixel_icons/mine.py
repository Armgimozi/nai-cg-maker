from __future__ import annotations

from . import SIZE, add_ramps, edge, paint, register

NAMES: dict[str, str] = {}


def icon(iid, name, slots, *maps, legend=None, rim=False):
    """아이템 id · 한글 이름(설명용) · slot→램프 이름 · 지도들 (차례로 덮음).
    rim=True 면 첫 지도를 칠한 뒤 edge() 로 R4 테두리 (위·왼쪽 2 / 아래·오른쪽 0) 를 그 물체 자기 램프로 두른다."""
    NAMES[iid] = name
    img = paint(slots, maps[0], legend=legend)
    if rim:
        img = edge(img, list(slots.values()))
    if len(maps) > 1:
        img = paint(slots, *maps[1:], legend=legend, img=img)
    register(iid, lambda ctx, _i=img: _i.copy(), group='mine')
    return img


def grid(text: str) -> list[str]:
    """16줄 × 16글자 지도 (줄 앞뒤 공백 무시). 크기가 틀리면 바로 오류 — 지도를 잘못 고친 것을 import 때 잡는다."""
    out = [ln.strip() for ln in text.strip('\n').split('\n')]
    if len(out) != SIZE or any(len(r) != SIZE for r in out):
        raise ValueError(f'mine map must be {SIZE}x{SIZE}: {[len(r) for r in out]}')
    return out


