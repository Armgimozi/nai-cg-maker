from __future__ import annotations

from . import E, SIZE, add_ramps, register_maps

NAMES: dict[str, str] = {}


def icon(iid, name, slots, *maps, legend=None):
    """아이템 id · 한글 이름(설명용) · slot→램프 이름 · 지도들 (차례로 덮음)."""
    NAMES[iid] = name
    return register_maps(iid, slots, *maps, legend=legend, group='mine')


def grid(text: str) -> list[str]:
    """16줄 × 16글자 지도 (줄 앞뒤 공백 무시). 크기가 틀리면 바로 오류 — 지도를 잘못 고친 것을 import 때 잡는다."""
    out = [ln.strip() for ln in text.strip('\n').split('\n')]
    if len(out) != SIZE or any(len(r) != SIZE for r in out):
        raise ValueError(f'mine map must be {SIZE}x{SIZE}: {[len(r) for r in out]}')
    return out


